export type TranslationKeys = typeof translations.id;

export function getTranslation(lang: Language) {
  return translations[lang];
}

export function formatCurrency(amount: number, lang: Language = 'id'): string {
  if (lang === 'en') {
    return new Intl.NumberFormat('en-US', { style: 'currency', currency: 'IDR', maximumFractionDigits: 0 }).format(amount);
  }
  return `Rp${amount.toLocaleString('id-ID')}`;
}
